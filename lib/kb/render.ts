/**
 * Renders the knowledge base as Markdown (docs/guide) and JSON (docs/agents/kb.json).
 *
 * Pure: content in, strings out. scripts/gen-docs.ts writes the files (`npm run docs`) and
 * lib/kb/docs.test.ts fails when the files on disk no longer match, so the published guides
 * cannot drift from what the app and Ask AI say.
 */
import { GLOSSARY, GLOSSARY_KEYS, type GlossaryEntry } from '@/lib/glossary';
import { QB_NOT_A_MENU_NAME } from '@/lib/nav';
import { KB_ARTICLES, KB_AREAS, KB_AREA_ORDER, KB_SCREENS, linksOf, menuPath, type KbArea, type KbArticle, type KbLink, type KbScreen } from './index';

export const GENERATED_NOTE =
  '<!-- Generated by `npm run docs` from lib/kb/articles.ts, lib/nav.ts, lib/pageHelp.ts and lib/glossary.ts. Do not edit by hand: change the source and run `npm run docs`. -->';

export const AREA_FILE: Record<KbArea, string> = {
  start: 'getting-started.md',
  sales: 'customers-and-sales.md',
  purchases: 'vendors-and-purchases.md',
  banking: 'banking.md',
  accounting: 'accounting-and-closing.md',
  payroll: 'employees-and-payroll.md',
  inventory: 'items-and-inventory.md',
  reports: 'reports.md',
  file: 'company-file-backup-users.md',
  ai: 'ai-and-automation.md',
  quickbooks: 'coming-from-quickbooks.md',
  fixes: 'fixing-things.md',
};

/** Table-cell safe text. */
const cell = (s: string | undefined) => (s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/** Where a link is: "**Sales › Invoices** (`/invoices?new=1`)". */
function place(l: KbLink): string {
  // A link that opens something particular on a page ('?assistant=1', '?type=cc_charge') is named
  // by its own label; a plain page (or its '?new=1' form) by where it sits in the menu.
  const query = l.href.split('?')[1]?.split('#')[0] ?? '';
  const menu = query && query !== 'new=1' ? null : menuPath(l.href);
  return menu ? `**${menu}** (\`${l.href}\`)` : `**${l.label}** (\`${l.href}\`)`;
}

function renderArticle(a: KbArticle): string {
  const out: string[] = [];
  out.push(`## ${a.title}`, '', `<a id="${a.id}"></a>`, '', a.summary, '');
  if (a.go) out.push(`**Where:** ${place(a.go)}`, '');
  a.steps.forEach((s, i) => {
    out.push(`${i + 1}. ${s.text}${s.link ? ` → ${place(s.link)}` : ''}`);
  });
  if (a.notes?.length) {
    out.push('');
    for (const n of a.notes) out.push(`> Good to know: ${n}`, '>');
    out.pop();
  }
  out.push('', `*In the app: Help & Glossary → "${a.title}", or ask Ask AI.*`, '');
  return out.join('\n');
}

export function renderAreaGuide(area: KbArea): string {
  const list = KB_ARTICLES.filter((a) => a.area === area);
  return [
    `# ${KB_AREAS[area].title}`,
    '',
    GENERATED_NOTE,
    '',
    KB_AREAS[area].blurb,
    '',
    'Paths such as `/invoices` are in-app addresses: press **Ctrl+K** in Ironbooks and type the screen’s name to open it.',
    '',
    ...list.map((a) => `- [${a.title}](#${a.id})`),
    '',
    '---',
    '',
    ...list.map(renderArticle),
    '[← All guides](./README.md)',
    '',
  ].join('\n');
}

export function renderGuideIndex(): string {
  const out: string[] = [
    '# Ironbooks user guide',
    '',
    GENERATED_NOTE,
    '',
    'Short answers to "how do I…?", each with the screen to open. The same guides are inside the app under **Help & Glossary**, and **Ask AI** answers from them and links you straight to the screen.',
    '',
    'New here? Start with [START-HERE](../START-HERE.md).',
    '',
  ];
  for (const area of KB_AREA_ORDER) {
    const list = KB_ARTICLES.filter((a) => a.area === area);
    if (!list.length) continue;
    out.push(`## [${KB_AREAS[area].title}](./${AREA_FILE[area]})`, '', KB_AREAS[area].blurb, '');
    for (const a of list) out.push(`- [${a.title}](./${AREA_FILE[area]}#${a.id})`);
    out.push('');
  }
  out.push(
    '## Reference',
    '',
    '- [Every screen](./screens.md): what each screen is for, its menu and its QuickBooks name.',
    '- [QuickBooks names](./quickbooks-names.md): find the Ironbooks screen for a QuickBooks Desktop screen.',
    '- [Glossary](./glossary.md): accounting terms in plain language.',
    '',
  );
  return out.join('\n');
}

const GROUP_ORDER = ['Home', 'Sales', 'Customers', 'Purchases', 'Vendors', 'Banking', 'Accounting', 'Employees', 'Reports', 'Admin', 'Operations', 'Setup', 'Company', 'Other'];

function groupsOfScreens(): [string, KbScreen[]][] {
  const by = new Map<string, KbScreen[]>();
  for (const s of KB_SCREENS) by.set(s.group, [...(by.get(s.group) ?? []), s]);
  return [...by.entries()].sort((a, b) => {
    const ia = GROUP_ORDER.indexOf(a[0]);
    const ib = GROUP_ORDER.indexOf(b[0]);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
  });
}

export function renderScreens(): string {
  const out: string[] = [
    '# Every screen',
    '',
    GENERATED_NOTE,
    '',
    `All ${KB_SCREENS.length} screens the menus and the help know about, grouped as in the **Advanced** menu. "Simple menu" shows the name a screen has in the shorter everyday menu. To open any of them, press **Ctrl+K** and type its name or its QuickBooks name.`,
    '',
  ];
  for (const [group, screens] of groupsOfScreens()) {
    out.push(`## ${group === 'Other' ? 'Other screens (not in the menu)' : group}`, '', '| Screen | Path | QuickBooks name | What it is for | First step |', '|---|---|---|---|---|');
    for (const s of screens) {
      const name = s.simpleLabel && s.simpleLabel !== s.label ? `${s.label} (Simple menu: ${s.simpleLabel})` : s.label;
      out.push(`| ${cell(name)} | \`${s.path}\` | ${cell(s.qb)} | ${cell(s.what)} | ${cell(s.first)} |`);
    }
    out.push('');
  }
  out.push('[← All guides](./README.md)', '');
  return out.join('\n');
}

export function renderQuickBooksNames(): string {
  // Only real QuickBooks screen names: some `qb` notes just describe an Ironbooks-only screen.
  const rows = KB_SCREENS.filter((s) => s.qb && s.group !== 'Other' && !QB_NOT_A_MENU_NAME.has(s.qb) && !/Ironbooks/.test(s.qb)).sort((a, b) => a.qb!.localeCompare(b.qb!, 'en'));
  return [
    '# QuickBooks names',
    '',
    GENERATED_NOTE,
    '',
    'Coming from QuickBooks Desktop? Find the screen you know on the left. In Ironbooks, press **Ctrl+K** and type either name. To make the menus use QuickBooks names, turn on **Use QuickBooks names in the menu** in My Preferences.',
    '',
    '| In QuickBooks Desktop | In Ironbooks | Menu | Path |',
    '|---|---|---|---|',
    ...rows.map((s) => `| ${cell(s.qb)} | ${cell(s.label)} | ${cell(menuPath(s.path) ?? '')} | \`${s.path}\` |`),
    '',
    '[← All guides](./README.md)',
    '',
  ].join('\n');
}

export function renderGlossary(): string {
  const out: string[] = ['# Glossary', '', GENERATED_NOTE, '', 'Accounting terms in plain language. In the app, hover the ? beside a term, or open Help & Glossary.', ''];
  for (const key of GLOSSARY_KEYS) {
    const e: GlossaryEntry = GLOSSARY[key];
    out.push(`## ${e.term}`, '', `<a id="term-${key}"></a>`, '', e.short, '');
    if (e.long) out.push(e.long, '');
    if (e.aliases?.length) out.push(`*Also called: ${e.aliases.join(', ')}.*`, '');
  }
  out.push('[← All guides](./README.md)', '');
  return out.join('\n');
}

/** The knowledge base as data, for agents and tools (docs/agents/kb.json). */
export function renderKbJson(): string {
  const data = {
    about:
      'Ironbooks product knowledge base. Generated by `npm run docs` from lib/kb/articles.ts, lib/nav.ts, lib/pageHelp.ts and lib/glossary.ts; do not edit. `href`/`path` values are in-app addresses. For the code behind a screen see docs/agents/code-map.md.',
    areas: KB_AREA_ORDER.map((id) => ({ id, ...KB_AREAS[id], guide: `docs/guide/${AREA_FILE[id]}` })),
    articles: KB_ARTICLES.map((a) => ({
      id: a.id,
      area: a.area,
      title: a.title,
      summary: a.summary,
      go: a.go ? { ...a.go, menu: menuPath(a.go.href) } : null,
      steps: a.steps.map((s) => ({ text: s.text, ...(s.link ? { link: s.link } : {}) })),
      notes: a.notes ?? [],
      asks: a.asks,
      links: linksOf(a).map((l) => l.href),
    })),
    screens: KB_SCREENS.map((s) => ({
      path: s.path,
      label: s.label,
      group: s.group,
      menu: menuPath(s.path),
      ...(s.simpleLabel ? { simpleLabel: s.simpleLabel } : {}),
      ...(s.qb ? { quickbooks: s.qb } : {}),
      ...(s.what ? { what: s.what } : {}),
      ...(s.first ? { first: s.first } : {}),
    })),
    glossary: GLOSSARY_KEYS.map((key) => {
      const e: GlossaryEntry = GLOSSARY[key];
      return { key, term: e.term, short: e.short, ...(e.long ? { long: e.long } : {}), aliases: e.aliases ?? [] };
    }),
  };
  return JSON.stringify(data, null, 2) + '\n';
}

/** Every generated guide file: repo-relative path → content. */
export function guideFiles(): Record<string, string> {
  const files: Record<string, string> = {
    'docs/guide/README.md': renderGuideIndex(),
    'docs/guide/screens.md': renderScreens(),
    'docs/guide/quickbooks-names.md': renderQuickBooksNames(),
    'docs/guide/glossary.md': renderGlossary(),
    'docs/agents/kb.json': renderKbJson(),
  };
  for (const area of KB_AREA_ORDER) files[`docs/guide/${AREA_FILE[area]}`] = renderAreaGuide(area);
  return files;
}
